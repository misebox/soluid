/**
 * Regenerates src/soluid-all.css: one @import per component stylesheet.
 *
 * This is the single aggregate every local build consumes — the catalog
 * (src/dev/App.tsx) and the sample apps (src/samples/shared.css). Keeping one
 * generated list means adding a component never needs a hand-edited import.
 *
 * Run: bun run generate:css
 */

import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const componentsDir = path.resolve(__dirname, "../src/components/ui/soluid");
const outPath = path.resolve(__dirname, "../src/soluid-all.css");

/** @import paths resolve against this file's own location, not the importer's. */
const IMPORT_PREFIX = "./components/ui/soluid";

const cssFiles = fs
  .readdirSync(componentsDir)
  .filter((f) => f.endsWith(".css"))
  .sort();

const content = [
  "/* Generated by scripts/generate-css-imports.ts — do not edit. */",
  `@import "${IMPORT_PREFIX}/core/soluid.css";`,
  ...cssFiles.map((f) => `@import "${IMPORT_PREFIX}/${f}";`),
  "",
].join("\n");

fs.writeFileSync(outPath, content);
console.log(`Generated ${cssFiles.length} CSS imports -> ${outPath}`);
